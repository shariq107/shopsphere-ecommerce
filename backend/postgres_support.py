def _translate_sql(statement):
    """Translate the few SQLite SQL constructs used by app.py to PostgreSQL."""
    sql = statement.strip()
    ignore_insert = bool(re.search(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", sql, re.I))

    sql = re.sub(
        r"\bINSERT\s+OR\s+IGNORE\s+INTO\b",
        "INSERT INTO",
        sql,
        flags=re.I,
    )
    sql = sql.replace("?", "%s")

    # SQLite datetime(?) <= datetime('now') used for coupon expiry checks.
    sql = re.sub(r"\bdatetime\s*\(\s*%s\s*\)", "(%s::timestamp)", sql, flags=re.I)
    sql = re.sub(r"\bdatetime\s*\(\s*'now'\s*\)", "CURRENT_TIMESTAMP", sql, flags=re.I)

    # SQLite date(...) is used by the admin date-filtered reports.
    sql = re.sub(
        r"\bdate\s*\(\s*((?:orders\.)?created_at)\s*\)",
        r"(\1::date)",
        sql,
        flags=re.I,
    )
    sql = re.sub(r"\bdate\s*\(\s*%s\s*\)", "(%s::date)", sql, flags=re.I)

    if ignore_insert:
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return sql


class PostgreSQLCursor:
    """Small cursor wrapper for SQLite-style fetches and lastrowid."""

    def __init__(self, raw_cursor):
        self._cursor = raw_cursor
        self._lastrowid = None

    def execute(self, statement, parameters=None):
        sql = _translate_sql(statement)
        self._lastrowid = None
        is_insert = bool(re.match(r"\s*INSERT\s+INTO\s+", sql, re.I))

        # PostgreSQL does not expose SQLite's lastrowid. RETURNING id gives us
        # the generated ID while preserving the existing app.py call sites.
        if is_insert and not re.search(r"\bRETURNING\b", sql, re.I):
            sql = sql.rstrip().rstrip(";") + " RETURNING id"

        self._cursor.execute(sql, parameters or ())
        if is_insert:
            inserted = self._cursor.fetchone()
            if inserted is not None:
                self._lastrowid = inserted[0]
        return self

    def executemany(self, statement, parameter_rows):
        self._lastrowid = None
        self._cursor.executemany(_translate_sql(statement), parameter_rows)
        return self

    @property
    def lastrowid(self):
        return self._lastrowid

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def close(self):
        self._cursor.close()

    def __getattr__(self, name):
        return getattr(self._cursor, name)


class PostgreSQLConnection:
    def __init__(self, raw_connection):
        self._connection = raw_connection

    def cursor(self):
        return PostgreSQLCursor(self._connection.cursor())

    def execute(self, statement, parameters=None):
        return self.cursor().execute(statement, parameters)

    def executemany(self, statement, parameter_rows):
        return self.cursor().executemany(statement, parameter_rows)

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()

    def close(self):
        self._connection.close()

    def __getattr__(self, name):
        return getattr(self._connection, name)


def get_postgres_db():
    if psycopg2 is None:
        raise RuntimeError(
            "DATABASE_URL is set, but psycopg2 is not installed. Run: "
            "python -m pip install -r requirements.txt"
        )

    database_url = os.environ.get("DATABASE_URL", "").strip()
    if not database_url:
        raise RuntimeError("DATABASE_URL is empty")

    raw = psycopg2.connect(
        database_url,
        cursor_factory=DictCursor,
        connect_timeout=15,
    )
    return PostgreSQLConnection(raw)


def initialize_postgres_database():
    """Create/upgrade the PostgreSQL schema without dropping existing data."""
    connection = get_postgres_db()
    try:
        cursor = connection.cursor()
        for statement in POSTGRES_SCHEMA:
            cursor.execute(statement)

        # Safe additive upgrades for an earlier/partially-created schema.
        cursor.execute("ALTER TABLE products ADD COLUMN IF NOT EXISTS image TEXT DEFAULT ''")
        cursor.execute("ALTER TABLE products ADD COLUMN IF NOT EXISTS stock INTEGER NOT NULL DEFAULT 0")
        cursor.execute("ALTER TABLE orders ADD COLUMN IF NOT EXISTS coupon_code TEXT")
        cursor.execute("ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount DOUBLE PRECISION NOT NULL DEFAULT 0")

        default_coupons = [
            ("WELCOME10", "percentage", 10, 500, 200, 1, None),
            ("FLAT100", "fixed", 100, 1000, None, 1, None),
        ]
        for coupon in default_coupons:
            cursor.execute(
                """INSERT INTO coupons
                   (code, discount_type, discount_value, minimum_order,
                    maximum_discount, is_active, expires_at)
                   VALUES (?, ?, ?, ?, ?, ?, ?)
                   ON CONFLICT (code) DO NOTHING""",
                coupon,
            )

        product_count = connection.execute(
            "SELECT COUNT(*) FROM products"
        ).fetchone()[0]

        if product_count == 0:
            connection.executemany(
                """INSERT INTO products
                   (name, category, price, old_price, label, art, color, image, stock)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                [
                    ("Classic T-Shirt", "Clothing", 499, 699, "Popular", "T", "#e8e8e8", "", 20),
                    ("Running Shoes", "Footwear", 1499, 1999, "Trending", "S", "#dce8f5", "", 15),
                    ("Smart Watch", "Electronics", 2499, 2999, "New", "W", "#e5e0f2", "", 10),
                    ("Backpack", "Accessories", 899, 1199, "", "B", "#e8e2d8", "", 12),
                    ("Wireless Headphones", "Electronics", 1799, 2299, "Popular", "H", "#e2e8e4", "", 8),
                    ("Casual Sneakers", "Footwear", 1299, 1699, "", "C", "#f0e5df", "", 18),
                ],
            )

        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()
